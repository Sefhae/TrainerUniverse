/* ─── Spanish (es) ───
   Built by deep-merging Spanish overrides over the full English tree, so any key
   not yet translated falls back to English instead of breaking. */
type Overrides = { [k: string]: unknown };

function deepMerge<T>(base: T, over: Overrides): T {
  const out: Record<string, unknown> = { ...(base as Record<string, unknown>) };
  for (const [k, ov] of Object.entries(over)) {
    const bv = out[k];
    if (ov && typeof ov === 'object' && !Array.isArray(ov) && bv && typeof bv === 'object' && !Array.isArray(bv)) {
      out[k] = deepMerge(bv, ov as Overrides);
    } else {
      out[k] = ov;
    }
  }
  return out as T;
}

